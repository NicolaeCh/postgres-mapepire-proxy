import assert from 'node:assert/strict';
import { translateSql } from '../dist/src/sql/translator.js';

const opts = {
  uppercaseIdentifiers: true,
  informationSchemaRewrite: true,
  pgCatalogCompat: true,
  allowMultiStatement: false,
  maxRows: 0,
};

const create = translateSql(
  'create table monai.serial_test (id serial primary key, serial integer)', opts,
).sql;
assert.match(create, /ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
assert.match(create, /SERIAL INTEGER/);
assert.match(translateSql('create table monai.small_serial_test (id smallserial)', opts).sql, /ID SMALLINT GENERATED BY DEFAULT AS IDENTITY/);
assert.match(translateSql('create table monai.big_serial_test (id bigserial)', opts).sql, /ID BIGINT GENERATED BY DEFAULT AS IDENTITY/);
assert.throws(() => translateSql('create table monai.bad (a serial, b serial)', opts), /only one identity column/i);

assert.equal(
  translateSql('alter table token_usage_logs alter column id type integer', opts).sql,
  'ALTER TABLE TOKEN_USAGE_LOGS ALTER COLUMN ID SET DATA TYPE INTEGER',
);
assert.equal(
  translateSql('alter table app.t alter c type varchar', opts).sql,
  'ALTER TABLE APP.T ALTER COLUMN C SET DATA TYPE VARCHAR(1024)',
);
assert.throws(
  () => translateSql('alter table app.t alter c type integer using cast(c as integer)', opts),
  /TYPE .* USING/i,
);

const exists = translateSql(
  "select exists(select 1 from information_schema.tables where table_schema='MONAI') as present", opts,
).sql;
assert.match(exists, /CASE WHEN EXISTS \(SELECT 1 FROM SYSIBM\.TABLES/);
assert.match(exists, /THEN 1 ELSE 0 END AS PRESENT FROM SYSIBM\.SYSDUMMY1/);

console.log('PostgreSQL-to-Db2 DDL/scalar translation check OK');
