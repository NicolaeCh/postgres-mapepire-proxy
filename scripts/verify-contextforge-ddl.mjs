import assert from 'node:assert/strict';
import { translateSql } from '../dist/src/sql/translator.js';

const options = {
  uppercaseIdentifiers: true,
  informationSchemaRewrite: true,
  pgCatalogCompat: true,
  allowMultiStatement: false,
  maxRows: 0,
  ddlDefaultVarcharLength: 1024,
};

const gateways = translateSql(`CREATE TABLE gateways (
  id VARCHAR(36) NOT NULL,
  name VARCHAR NOT NULL,
  slug VARCHAR NOT NULL,
  url VARCHAR NOT NULL,
  description VARCHAR,
  transport VARCHAR NOT NULL,
  capabilities JSON NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  is_active BOOLEAN NOT NULL,
  last_seen TIMESTAMP,
  auth_type VARCHAR,
  auth_value JSON,
  PRIMARY KEY (id),
  UNIQUE (slug),
  UNIQUE (url)
)`, options).sql;

assert.match(gateways, /NAME VARCHAR\(1024\) NOT NULL/i);
assert.match(gateways, /CAPABILITIES CLOB\(2G\) CCSID 1208 NOT NULL/i);
assert.match(gateways, /CREATED_AT TIMESTAMP NOT NULL/i);
assert.doesNotMatch(gateways, /\bJSONB?\b/i);
assert.doesNotMatch(gateways, /TIMESTAMP WITH TIME ZONE/i);
assert.doesNotMatch(gateways, /\bVARCHAR\s+(?:NOT|NULL|,)/i);

const resources = translateSql(`CREATE TABLE resources (
  id SERIAL PRIMARY KEY,
  text_content TEXT,
  binary_content BYTEA
)`, options).sql;
assert.match(resources, /ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/i);
assert.match(resources, /TEXT_CONTENT CLOB\(2G\) CCSID 1208/i);
assert.match(resources, /BINARY_CONTENT BLOB\(2G\)/i);

const altered = translateSql('ALTER TABLE gateways ADD COLUMN metadata JSONB', options).sql;
assert.match(altered, /ADD COLUMN METADATA CLOB\(2G\) CCSID 1208/i);

console.log('ContextForge PostgreSQL DDL -> Db2 for i compatibility check OK');
