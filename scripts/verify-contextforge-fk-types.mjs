import assert from 'node:assert/strict';
import { DdlForeignKeyTypeRegistry } from '../dist/src/sql/ddl-foreign-key.js';

const registry = new DdlForeignKeyTypeRegistry();
const schema = 'MCPDATA';

registry.registerCreateTable(`CREATE TABLE SERVERS (
  ID VARCHAR(36) NOT NULL,
  NAME VARCHAR(1024) NOT NULL,
  CONSTRAINT PK_SERVERS PRIMARY KEY (ID)
)`, schema);

let aligned = registry.alignCreateTable(`CREATE TABLE SERVER_METRICS (
  ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  SERVER_ID VARCHAR(1024) NOT NULL,
  TIMESTAMP TIMESTAMP NOT NULL,
  RESPONSE_TIME FLOAT NOT NULL,
  IS_SUCCESS BOOLEAN NOT NULL,
  ERROR_MESSAGE CLOB(2G) CCSID 1208,
  CONSTRAINT PK_SERVER_METRICS PRIMARY KEY (ID),
  CONSTRAINT FK_SERVER_METRICS_SERVER_ID FOREIGN KEY(SERVER_ID) REFERENCES SERVERS (ID)
)`, schema);

assert.match(aligned.sql, /SERVER_ID VARCHAR\(36\) NOT NULL/i);
assert.equal(aligned.alignments.length, 1);
assert.equal(aligned.alignments[0].parentTable, 'SERVERS');
assert.equal(aligned.alignments[0].parentColumn, 'ID');
assert.equal(aligned.alignments[0].alignedType, 'VARCHAR(36)');
registry.registerCreateTable(aligned.sql, schema);

registry.registerCreateTable(`CREATE TABLE TOOLS (
  ID VARCHAR(36) NOT NULL,
  NAME VARCHAR(1024),
  CONSTRAINT PK_TOOLS PRIMARY KEY (ID)
)`, schema);

aligned = registry.alignCreateTable(`CREATE TABLE SERVER_TOOL_ASSOCIATION (
  SERVER_ID VARCHAR(1024) NOT NULL,
  TOOL_ID VARCHAR(1024) NOT NULL,
  CONSTRAINT FK_STA_SERVER FOREIGN KEY(SERVER_ID) REFERENCES SERVERS (ID),
  CONSTRAINT FK_STA_TOOL FOREIGN KEY(TOOL_ID) REFERENCES TOOLS (ID),
  CONSTRAINT PK_STA PRIMARY KEY (SERVER_ID, TOOL_ID)
)`, schema);
assert.match(aligned.sql, /SERVER_ID VARCHAR\(36\) NOT NULL/i);
assert.match(aligned.sql, /TOOL_ID VARCHAR\(36\) NOT NULL/i);
assert.equal(aligned.alignments.length, 2);

registry.registerCreateTable(`CREATE TABLE MCP_SESSIONS (
  SESSION_ID VARCHAR(1024) NOT NULL,
  CONSTRAINT PK_MCP_SESSIONS PRIMARY KEY (SESSION_ID)
)`, schema);
aligned = registry.alignCreateTable(`CREATE TABLE MCP_MESSAGES (
  ID INTEGER NOT NULL,
  SESSION_ID VARCHAR(1024) NOT NULL,
  CONSTRAINT FK_MCP_MESSAGES_SESSION FOREIGN KEY(SESSION_ID) REFERENCES MCP_SESSIONS (SESSION_ID)
)`, schema);
assert.match(aligned.sql, /SESSION_ID VARCHAR\(1024\) NOT NULL/i);
assert.equal(aligned.alignments.length, 0);

console.log('ContextForge Db2 foreign-key datatype compatibility check OK');
